import "./dotenv.js";
import { pool } from "./database.js";
import events from "../data/events.js";
import rsvps from "../data/rsvps.js";
import users from "../data/users.js";

const schemaStatements = [
  `CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    city TEXT NOT NULL,
    user_image_url TEXT,
    user_type TEXT NOT NULL CHECK (user_type IN ('host', 'attendee'))
  )`,
  `CREATE TABLE IF NOT EXISTS events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    event_title TEXT NOT NULL,
    event_start_time TIME NOT NULL,
    event_date DATE NOT NULL,
    event_duration INTEGER NOT NULL CHECK (event_duration > 0),
    event_image_url TEXT,
    event_location TEXT,
    online_link_url TEXT,
    event_type TEXT NOT NULL,
    CONSTRAINT events_host_title_date_time_unique
      UNIQUE (host_user_id, event_title, event_date, event_start_time)
  )`,
  `CREATE TABLE IF NOT EXISTS rsvp (
    rsvp_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    event_id BIGINT NOT NULL REFERENCES events(event_id) ON DELETE CASCADE,
    rsvp_status TEXT NOT NULL DEFAULT 'attending'
      CHECK (rsvp_status IN ('attending', 'not_attending', 'cancelled')),
    CONSTRAINT rsvp_user_event_unique UNIQUE (user_id, event_id)
  )`,
  "CREATE INDEX IF NOT EXISTS events_date_idx ON events(event_date)",
  "CREATE INDEX IF NOT EXISTS events_host_user_id_idx ON events(host_user_id)",
  "CREATE INDEX IF NOT EXISTS rsvp_event_id_idx ON rsvp(event_id)",
  "CREATE INDEX IF NOT EXISTS rsvp_user_id_idx ON rsvp(user_id)",
];

async function seed(client) {
  for (const user of users) {
    await client.query(
      `INSERT INTO users (full_name, email, city, user_image_url, user_type)
       VALUES ($1, $2, $3, $4, $5)
       ON CONFLICT (email) DO UPDATE SET
         full_name = EXCLUDED.full_name,
         city = EXCLUDED.city,
         user_image_url = EXCLUDED.user_image_url,
         user_type = EXCLUDED.user_type`,
      [
        user.fullName,
        user.email,
        user.city,
        user.userImageUrl,
        user.userType,
      ],
    );
  }

  const userIds = new Map(
    (
      await client.query(
        "SELECT user_id, email FROM users WHERE email = ANY($1::text[])",
        [users.map((user) => user.email)],
      )
    ).rows.map((row) => [row.email, row.user_id]),
  );
  const eventIds = [];

  for (const event of events) {
    const hostUserId = userIds.get(event.hostEmail);
    if (!hostUserId) {
      throw new Error(`Seed host not found for event: ${event.eventTitle}`);
    }
    const result = await client.query(
      `INSERT INTO events (
         host_user_id, event_title, event_start_time, event_date,
         event_duration, event_image_url, event_location,
         online_link_url, event_type
       )
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
       ON CONFLICT (host_user_id, event_title, event_date, event_start_time)
       DO UPDATE SET
         event_duration = EXCLUDED.event_duration,
         event_image_url = EXCLUDED.event_image_url,
         event_location = EXCLUDED.event_location,
         online_link_url = EXCLUDED.online_link_url,
         event_type = EXCLUDED.event_type
       RETURNING event_id`,
      [
        hostUserId,
        event.eventTitle,
        event.eventStartTime,
        event.eventDate,
        event.eventDuration,
        event.eventImageUrl,
        event.eventLocation,
        event.onlineLinkUrl,
        event.eventType,
      ],
    );
    eventIds.push(result.rows[0].event_id);
  }

  for (const rsvp of rsvps) {
    const userId = userIds.get(rsvp.attendeeEmail);
    const eventId = eventIds[rsvp.eventIndex];
    if (!userId || !eventId) {
      throw new Error(`Seed RSVP reference is invalid at event ${rsvp.eventIndex}.`);
    }
    await client.query(
      `INSERT INTO rsvp (user_id, event_id, rsvp_status)
       VALUES ($1, $2, $3)
       ON CONFLICT (user_id, event_id)
       DO UPDATE SET rsvp_status = EXCLUDED.rsvp_status`,
      [userId, eventId, rsvp.rsvpStatus],
    );
  }
}

async function resetDatabase() {
  const client = await pool.connect();
  let transactionStarted = false;
  try {
    await client.query("BEGIN");
    transactionStarted = true;
    for (const statement of schemaStatements) {
      await client.query(statement);
    }
    await seed(client);
    await client.query("COMMIT");
    transactionStarted = false;

    const counts = await client.query(
      `SELECT
         (SELECT count(*)::int FROM users) AS users,
         (SELECT count(*)::int FROM events) AS events,
         (SELECT count(*)::int FROM rsvp) AS rsvps`,
    );
    console.log("Database schema is ready and sample data is seeded.");
    console.log(JSON.stringify(counts.rows[0], null, 2));
  } catch (error) {
    if (transactionStarted) {
      try {
        await client.query("ROLLBACK");
      } catch {
        console.error("Database rollback could not be completed.");
      }
    }
    console.error(
      "Database setup failed:",
      error.code || error.name || "database error",
    );
    process.exitCode = 1;
  } finally {
    client.release();
    await pool.end();
  }
}

resetDatabase().catch(async (error) => {
  console.error(
    "Database setup failed:",
    error.code || error.name || "database connection error",
  );
  process.exitCode = 1;
  await pool.end();
});

import { pathToFileURL } from 'node:url'
import './dotenv.js' // must load first so process.env is set before the pool is created
import { pool } from './database.js'
import userData from '../data/users.js'
import venueData from '../data/venues.js'
import groupData from '../data/groups.js'
import memberData from '../data/members.js'
import eventData from '../data/events.js'
import rsvpData from '../data/rsvps.js'

// the words each fixed-choice column is allowed to hold
const USER_TYPES = ['host', 'attendee']
const RSVP_STATUSES = ['attending', 'not_attending']
const CATEGORIES = ['Technology', 'Arts', 'Food', 'Outdoors', 'Career', 'Community', 'Music', 'Wellness', 'Education', 'Games']

// tables in the order they must be filled: a table can only point at tables before it
const TABLES = [
    { name: 'users', rows: userData },
    { name: 'venues', rows: venueData },
    { name: 'groups', rows: groupData },
    { name: 'members', rows: memberData },
    { name: 'events', rows: eventData },
    { name: 'rsvps', rows: rsvpData }
]

// Postgres allows at most this many values in a single query
const MAX_QUERY_VALUES = 65535

// turn ['a', 'b'] into 'a', 'b' so it can sit inside a SQL IN (...) list
const toSqlList = (words) => words.map((word) => `'${word}'`).join(', ')

const createTables = async (client) => {
    // drop children before parents so foreign keys never block the drop
    const tableNames = [...TABLES].reverse().map((table) => table.name)

    const createTablesQuery = `
        DROP TABLE IF EXISTS ${tableNames.join(', ')} CASCADE;

        CREATE TABLE users (
            user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            full_name TEXT NOT NULL,
            email TEXT UNIQUE,
            password_hash TEXT,
            city TEXT NOT NULL,
            state TEXT,
            country TEXT,
            zipcode TEXT,
            user_image_url TEXT,
            user_type TEXT NOT NULL CHECK (user_type IN (${toSqlList(USER_TYPES)})),
            github_id TEXT UNIQUE,
            github_username TEXT,
            is_onboarded BOOLEAN DEFAULT FALSE
        );

        CREATE TABLE venues (
            venue_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            venue_name TEXT NOT NULL,
            address TEXT NOT NULL,
            city TEXT NOT NULL,
            state CHAR(2) NOT NULL CHECK (state ~ '^[A-Z]{2}$'),
            postal_code TEXT NOT NULL,
            latitude NUMERIC(9, 6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
            longitude NUMERIC(9, 6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
            UNIQUE (venue_name, address, city)
        );

        CREATE TABLE groups (
            group_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            organizer_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
            group_name TEXT NOT NULL,
            description TEXT,
            category TEXT NOT NULL CHECK (category IN (${toSqlList(CATEGORIES)})),
            group_image_url TEXT
        );

        CREATE TABLE members (
            membership_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
            group_id BIGINT NOT NULL REFERENCES groups(group_id) ON DELETE CASCADE,
            joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            UNIQUE (user_id, group_id)
        );

        CREATE TABLE events (
            event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            group_id BIGINT NOT NULL REFERENCES groups(group_id) ON DELETE CASCADE,
            venue_id BIGINT NOT NULL REFERENCES venues(venue_id) ON DELETE RESTRICT,
            event_title TEXT NOT NULL,
            description TEXT NOT NULL,
            start_time TIMESTAMP NOT NULL,
            end_time TIMESTAMP NOT NULL,
            capacity INTEGER NOT NULL CHECK (capacity > 0),
            event_image_url TEXT,
            CHECK (end_time > start_time)
        );

        CREATE TABLE rsvps (
            rsvp_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
            event_id BIGINT NOT NULL REFERENCES events(event_id) ON DELETE CASCADE,
            rsvp_status TEXT NOT NULL DEFAULT 'attending' CHECK (rsvp_status IN (${toSqlList(RSVP_STATUSES)})),
            UNIQUE (user_id, event_id)
        );

        CREATE INDEX idx_users_email_lower ON users (lower(email));
        CREATE INDEX idx_groups_category ON groups (category);
        CREATE INDEX idx_members_group_id ON members (group_id);
        CREATE INDEX idx_venues_state_city ON venues (state, city);
        CREATE INDEX idx_events_start_time ON events (start_time);
        CREATE INDEX idx_events_group_id ON events (group_id);
        CREATE INDEX idx_events_venue_id ON events (venue_id);
        CREATE INDEX idx_rsvps_event_id ON rsvps (event_id);
    `

    try {
        await client.query(createTablesQuery)
        console.log('🎉 tables created successfully')
    } catch (err) {
        console.error('⚠️ error creating tables', err)
        throw err
    }
}

// insert one table's records, taking the column names from the records themselves
const seedTable = async (client, { name, rows }) => {
    // every record in a table has the same fields, so the first one names the columns
    const columns = Object.keys(rows[0])

    // send the records in chunks so no single query goes over the value limit
    const chunkSize = Math.floor(MAX_QUERY_VALUES / columns.length)

    try {
        for (let start = 0; start < rows.length; start += chunkSize) {
            const chunk = rows.slice(start, start + chunkSize)

            // build ($1, $2, ...) for each record and one flat list of values
            const values = chunk.flatMap((row) => columns.map((column) => row[column]))
            const placeholders = chunk
                .map((_, rowIndex) => `(${columns.map((_, columnIndex) => `$${rowIndex * columns.length + columnIndex + 1}`).join(', ')})`)
                .join(', ')

            await client.query(`INSERT INTO ${name} (${columns.join(', ')}) VALUES ${placeholders}`, values)
        }
        console.log(`✅ ${rows.length} ${name} added successfully`)
    } catch (err) {
        console.error(`⚠️ error inserting ${name}`, err)
        throw err
    }
}

// the records brought their own ids, so move each id counter past the highest one
const syncIdCounter = async (client, { name }) => {
    // ask the database which column is the table's id instead of writing it down here
    const identity = await client.query(
        `SELECT column_name FROM information_schema.columns
         WHERE table_schema = current_schema() AND table_name = $1 AND is_identity = 'YES'`,
        [name]
    )
    const idColumn = identity.rows[0].column_name

    await client.query(`SELECT setval(pg_get_serial_sequence('${name}', '${idColumn}'), (SELECT max(${idColumn}) FROM ${name}))`)
}

const resetDatabase = async () => {
    const client = await pool.connect()
    let transactionStarted = false

    try {
        // everything happens in one transaction so a failure leaves the database untouched
        await client.query('BEGIN')
        transactionStarted = true

        await createTables(client)

        // fill the tables in order: users first because other tables point at them
        for (const table of TABLES) {
            await seedTable(client, table)
            await syncIdCounter(client, table)
        }

        await client.query('COMMIT')
        transactionStarted = false
    } catch (err) {
        // undo the partial work, then report failure through the exit code
        if (transactionStarted) {
            await client.query('ROLLBACK').catch(() => console.error('⚠️ rollback could not be completed'))
        }
        console.error('⚠️ database reset failed:', err.message)
        process.exitCode = 1
    } finally {
        client.release()
        await pool.end()
    }
}

// only reset when this file is run directly, not when a test imports it
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    resetDatabase()
}

export { TABLES, createTables, seedTable, syncIdCounter }
